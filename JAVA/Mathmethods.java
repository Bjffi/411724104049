public class Mathmethods {
    public static void main(String[] args) {
        
    
        int a = 84;
        int b = 52;

        System.out.println("Min Value:"+Math.min(a, b));
        System.out.println("Max Value:"+Math.max(a, b));
        System.out.println(Math.abs(a));
        System.out.println("Power:"+Math.pow(a,2));
        System.out.println("Square:"+Math.sqrt(b));
        System.out.println("Round:"+Math.round(43.6));
        System.out.println("Ceil:"+Math.ceil(b));
        System.out.println("Floor:"+Math.floor(a));
    }

}
